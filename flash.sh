#!/usr/bin/env bash
#==========================================================================
#  piano64 烧录 —— 64 路加法分量钢琴，仅【按键发声】模式
#
#    ./flash.sh          下到 SRAM（掉电丢，调试用）
#    ./flash.sh -f       固化到 Flash（掉电不丢）
#
#  ⚠️ 接线（外置 PCM5102A 模块）
#
#        PCM5102A 模块        FPGA 板
#        ──────────────────   ──────────────────
#        LCK  ──────────────  P16   (J14 脚 6,  SDRAM1_D5)
#        DIN  ──────────────  R18   (J14 脚 8,  SDRAM1_D7)
#        BCK  ──────────────  V17   (J14 脚 10, SDRAM1_D14)
#        VIN  ──────────────  3V3
#        GND  ──────────────  GND
#
#  模块侧跳线：
#        SCK  → GND      （用内部 PLL，只要 3 根线）
#        FMT  → GND      （Philips I2S）
#        XSMT → 3V3      ★ 不接就一直静音
#        FLT / DEMP → GND
#
#  ── 按键（每个开关：一端接 J14 的 IO 脚，另一端接 GND = J14 脚 12）──
#     ★ 片内上拉：悬空读到 1，按下接地读到 0。不用外接电阻。
#     ★ 拿杜邦线碰一下 GND 就能当按键试。
#
#     KEY[0] do    (C4) = J14 脚 26   FPGA AA20
#     KEY[1] re    (D4) = J14 脚 25   FPGA AA21
#     KEY[2] mi    (E4) = J14 脚 24   FPGA AB21
#     KEY[3] fa    (F4) = J14 脚 23   FPGA AB22
#     KEY[4] sol   (G4) = J14 脚 22   FPGA Y21
#     KEY[5] la    (A4) = J14 脚 21   FPGA Y22
#     KEY[6] 模式键     = J14 脚 40   FPGA P14
#            按一下切一次：1 按键 → 2 指导小星星 → 3 指导欢乐颂 → 1
#
#  ── WS2812 灯带（数据 = T21 = J14 脚 4，VCC 用 J14 脚 11 或独立 5V，GND 必须共地）
#     ★ 灯带逻辑用原工程 ws2812_keyind.v（彩虹色轮），只删掉了八度指示条
#     ★★ 灯带前 6 颗（第 1~6 颗）是坏灯，实测第 7 颗往后完全正常
#        所以所有指示灯整体后移，前 6 颗永远发 0（保持黑）
#     第 7 颗  (索引 6)  = 乐器灯：白（钢琴）
#     第 8 颗  (索引 7)  = 模式灯：红=1按键  绿=2指导小星星  蓝=3指导欢乐颂
#     第 9~14 颗(索引 8~13)= 6 个按键灯（KEY[5]→第9颗 … KEY[0]→第14颗）
#         · 按下        → 彩虹色（全亮档）
#         · 指导·该按   → 彩虹色（全亮档）
#         · 指导·再下一个 → 彩虹色（1/16 暗档，预告）
#     第 12~16 颗 = 八度条【已删除，不亮】
#     其余灯全黑
#
#  ── 功能 ───────────────────────────────────────────────────────
#     · 6 个音符键自由弹，4 声部复音
#     · 每个音 64 路加法分量（赛题拓展 1：单音分量 ≥32 路）
#  ── 三个模式（按 KEY[7] 循环：1 → 2 → 3 → 1）──────────────────
#     模式1 按键发声   ：7 个键自由弹，灯带第 2 颗红
#     模式2 指导小星星 ：灯带指出下一个该按的键，按对才走下一个音，第 2 颗绿
#     模式3 指导欢乐颂 ：同上，谱子换成《欢乐颂》30 音，第 2 颗蓝
#
#     ★ 指导模式按错不会前进，按对才走
#     ★ 切进指导模式时从第 1 个音重新开始
#     · 没有八度切换、没有自动演奏、没有音色切换
#     · AB13 = 复位
#==========================================================================
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FS="$HERE/impl/pnr/piano64.fs"
[ -f "$FS" ] || { echo "找不到码流：$FS"; echo "先跑： ../../bin/gw_sh build.tcl"; exit 1; }

if [ "${1:-}" = "-f" ]; then MODE="Flash（掉电不丢）"; else MODE="SRAM（掉电丢）"; fi
echo "目标：$MODE"
echo "码流：$FS"
echo
sudo openFPGALoader -b tangmega138k --detect
echo
sudo openFPGALoader -b tangmega138k "$@" "$FS"
echo
echo "完成。6 个音符键 do re mi fa sol la，4 声部复音，64 分量钢琴音。"
echo "  KEY[6] 切模式：1=按键  2=指导小星星  3=指导欢乐颂；AB13 = 复位"
echo "  耳机插【PCM5102A 模块】的 3.5mm 口"
