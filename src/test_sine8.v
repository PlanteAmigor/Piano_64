//==========================================================================
//  test_sine8 —— 赛题「测试模式」音源：8 路纯正弦，固定不同频率
//
//  赛题原文（核心评分规则 3）：
//    「支持测试模式下输出多路不同频率音频，频谱可观测对应数量独立谱峰，
//      同时可通过 RTL 代码佐证纯硬件实时合成通路，验证无预录音频播放行为。」
//
//  ── 为什么必须是「纯正弦」而不是真实音色 ──────────────────────────
//    钢琴/古筝一个音就有 128 个分量，8 个声部叠起来是 1024 根谱线的
//    密集谐波森林，频谱仪上根本数不出「独立谱峰」。
//    这里的每一个键只发【一个】频率分量，按一个键屏上就亮一根柱。
//
//  ── 按键驱动（不是 8 路常开）────────────────────────────────
//    第 k 个音键 → 第 k 个频率，力度取 key_dual 双触点测出的真实力度。
//      按 1 个键 → 1 根柱；按住 3 个 → 3 根柱；松手立刻灭。
//    这样评委可以【自己上手试】：按哪个亮哪个，按几下亮几根，
//    直接证明这是实时硬件合成、而且频段确实是一一对应的，
//    而不是预先录好的一段 8 音和弦音频在循环播放。
//    力度还会影响柱高（按得越重柱越高），进一步佐证是实时信号。
//
//  ── 8 个频率：取 32 段频谱中 8 个【段的中心频率】──────────────────
//    段 2  / 6  / 10 / 14 / 18 / 22 / 26 / 30
//    58.88 / 127.55 / 276.33 / 598.66 / 1296.98 / 2809.85 / 6087.41 / 13188.11 Hz
//
//  ★ 为什么不用「8 个八度 C」：
//    先前用 C3..C10（130.8 … 16744），但 C7 = 2093 Hz 正好卡在段 20(1909)
//    与段 21(2316) 中间 → 屏幕上会显示两根半高的柱，评委数出来是 9 根。
//    改成段中心后，每路正好命中一段 → 8 根等高、干净的柱。
//
//  ★ 也不再是八度关系，所以不能用 INC0<<k，改成 8 个独立常量。
//
//    增量 = round(f × 2^32 / fs)，fs = 50MHz/16/64 = 48828.125 Hz
//
//  ── 资源 ────────────────────────────────────────────────────────
//    相位累加器：8 × 32 bit 寄存器
//    正弦表    ：复用 add_sine_lut（1024×32，2 块 BSRAM）
//    乘法器    ：1 个（时分复用，8 路轮流算）
//    时钟预算  ：每采样 1024 拍，本模块只用 ~50 拍（5%）
//
//  ── 为什么时分复用而不是 8 路并行 ────────────────────────────────
//    1024 拍里算 8 路绰绰有余，串行只需 1 个乘法器和 1 份正弦表，
//    并行则要 8 个乘法器 + 8 份表（16 块 BSRAM）。没有理由浪费。
//
//  ── 为什么必须插值 ──────────────────────────────────────────────
//    1024 点表直接取整会有相位截断杂散（实测 SNR 只有 48 dB），
//    线性插值后 ≈ 92 dB。测试信号必须是干净的，否则谱峰旁边全是杂线。
//==========================================================================
`default_nettype none

module test_sine8 (
    input  wire               clk,
    input  wire               rst_n,
    input  wire               tick,      // 采样节拍（48828.125 Hz）

    // ── 8 个音键（来自 key_dual，clk_sys 域）────────────────────
    //    key_on [k]      = 第 k 个键是否按住（双触点都闭合才算）
    //    key_vel[k*8+:8] = 第 k 个键的力度（击键越快越大）
    //    ✳ 测试模式不是「8 路一直在响」，而是【按哪个键响哪个单频】。
    //      按 1 个 → 1 根柱，按 3 个 → 3 根柱，松手就灭。
    input  wire        [7:0]  key_on,
    input  wire       [63:0]  key_vel,

    output reg  signed [15:0] sample     // 8 路合成后的样点
);

    // ══════════════════════════════════════════════════════════════
    //  频率增量（32 段频谱里段 2/6/10/14/18/22/26/30 的中心频率）
    // ══════════════════════════════════════════════════════════════

    wire [31:0] inc0 = 32'd5_178_746;      //   58.88 Hz  段 2
    wire [31:0] inc1 = 32'd11_219_521;     //  127.55 Hz  段 6
    wire [31:0] inc2 = 32'd24_306_588;     //  276.33 Hz  段 10
    wire [31:0] inc3 = 32'd52_659_129;     //  598.66 Hz  段 14
    wire [31:0] inc4 = 32'd114_083_634;    // 1296.98 Hz  段 18
    wire [31:0] inc5 = 32'd247_157_062;    // 2809.85 Hz  段 22
    wire [31:0] inc6 = 32'd535_454_658;    // 6087.41 Hz  段 26
    wire [31:0] inc7 = 32'd1_160_038_431;  // 13188.11 Hz 段 30

    // ══════════════════════════════════════════════════════════════
    //  每路增益 = 该键力度（没按住就是 0）
    //
    //  ★ 原来是写死的 255→150 阶梯（8 路常开）。现在改成取 key_dual
    //    测出的真实力度：按得越重柱越高，松手立刻归零。
    //    ➜ 屏上的柱高直接反映「这一下按得多用力」，比固定阶梯更有说服力。
    //
    //  ★ 8 路全按满、力度全 255 时的最坏峰值：
    //      单路幅度 = 32767×255/2048 = 4080
    //      8 路同相叠加 = 32639 < 32767  → 不会削顶
    //    这个定标和原来一致，所以频谱的满刻度参考（255）不用改。
    // ══════════════════════════════════════════════════════════════
    wire       cur_on   = key_on[k];
    wire [7:0] cur_vel  = key_vel[{k, 3'b000} +: 8];
    wire [7:0] cur_gain = cur_on ? cur_vel : 8'd0;

    // ══════════════════════════════════════════════════════════════
    //  8 路相位累加器（只在采样节拍上推进）
    // ══════════════════════════════════════════════════════════════
    reg [31:0] ph0, ph1, ph2, ph3, ph4, ph5, ph6, ph7;

    always @(posedge clk) begin
        if (!rst_n) begin
            ph0 <= 32'd0; ph1 <= 32'd0; ph2 <= 32'd0; ph3 <= 32'd0;
            ph4 <= 32'd0; ph5 <= 32'd0; ph6 <= 32'd0; ph7 <= 32'd0;
        end
        else if (tick) begin
            ph0 <= ph0 + inc0;
            ph1 <= ph1 + inc1;
            ph2 <= ph2 + inc2;
            ph3 <= ph3 + inc3;
            ph4 <= ph4 + inc4;
            ph5 <= ph5 + inc5;
            ph6 <= ph6 + inc6;
            ph7 <= ph7 + inc7;
        end
    end

    // 当前处理哪一路
    reg [2:0] k;
    reg [31:0] ph_cur;
    always @(*) begin
        case (k)
        3'd0:    ph_cur = ph0;
        3'd1:    ph_cur = ph1;
        3'd2:    ph_cur = ph2;
        3'd3:    ph_cur = ph3;
        3'd4:    ph_cur = ph4;
        3'd5:    ph_cur = ph5;
        3'd6:    ph_cur = ph6;
        default: ph_cur = ph7;
        endcase
    end

    // ══════════════════════════════════════════════════════════════
    //  正弦表（共用一份）
    // ══════════════════════════════════════════════════════════════
    reg  [9:0]  lut_a;
    wire [31:0] lut_d;

    add_sine_lut u_lut (
        .clk (clk),
        .addr(lut_a),
        .dout(lut_d)
    );

    // ══════════════════════════════════════════════════════════════
    //  时分复用状态机：6 拍 / 路 × 8 路 = 48 拍 / 采样
    // ══════════════════════════════════════════════════════════════
    localparam [2:0] S_IDLE    = 3'd0,
                     S_ADDR    = 3'd1,
                     S_LATCH   = 3'd2,
                     S_LATCH2  = 3'd3,
                     S_INTERP  = 3'd4,
                     S_INTERP2 = 3'd5,
                     S_ACC     = 3'd6,
                     S_OUT     = 3'd7;

    reg [2:0]  st;
    reg signed [15:0] dlo, dhi;         // 表中相邻两点 sin(i), sin(i+1)
    reg [9:0]  frac;                    // 插值系数 = ph[21:12]
    reg signed [26:0] ip;               // 插值乘法的宽中间值
    reg signed [15:0] s_int;            // 插值后的正弦值
    reg signed [23:0] acc;              // 8 路累加

    always @(posedge clk) begin
        if (!rst_n) begin
            st     <= S_IDLE;
            k      <= 3'd0;
            lut_a  <= 10'd0;
            dlo    <= 16'sd0;
            dhi    <= 16'sd0;
            frac   <= 10'd0;
            s_int  <= 16'sd0;
            acc    <= 24'sd0;
            ip     <= 27'sd0;
            sample <= 16'sd0;
        end
        else begin
            case (st)
            // ── 等采样节拍，清零累加器 ────────────────────────────
            S_IDLE: begin
                if (tick) begin
                    k   <= 3'd0;
                    acc <= 24'sd0;
                    st  <= S_ADDR;
                end
            end

            // ── 送表地址 ─────────────────────────────────────────
            S_ADDR: begin
                lut_a <= ph_cur[31:22];
                frac  <= ph_cur[21:12];
                st    <= S_LATCH;
            end

            // ── 取表（BSRAM 同步读，1 拍延迟）────────────────────
            //  ★★ 坑：add_sine_lut 是 always @(posedge clk) dout<=mem[addr]，
            //    S_ADDR 里 lut_a<=ph_cur 是非阻塞赋值，要到下一拍才生效；
            //    如果紧接着就在 S_LATCH 取 lut_d，拿到的是【上一个通道】的表值。
            //    现象：通道 k 用的是通道 k−1 的波形配上 k 的力度，
            //          幅度整体错位一位（ch0 拿到 vel240、ch7 拿到 vel255）。
            //    解法：中间空一拍再取。
            S_LATCH: begin
                st  <= S_LATCH2;
            end

            S_LATCH2: begin
                dlo <= lut_d[15:0];
                dhi <= lut_d[31:16];
                st  <= S_INTERP;
            end

            // ── 线性插值第一步：宽乘法（必须用 27 位中间值！）────────
            //  ★★ 踩过的坑：原来写成
            //        s_int <= dlo + (((dhi - dlo) * $signed({1'b0,frac})) >>> 10);
            //     右边整条表达式的上下文位宽 = s_int 的 16 位，
            //     Verilog 会把乘法结果【截断到 16 位】再移位：
            //     (hi−lo)×frac 最大可达 402×1023 = 411k，远大于 65535
            //     → 溢出回绕 → 重建出的正弦完全是垃圾。
            //     实测现象：8 根谱峰仍在但幅度全乱（每路拿到了邻居的力度）。
            S_INTERP: begin
                ip <= (dhi - dlo) * $signed({1'b0, frac});
                st <= S_INTERP2;
            end

            // ── 线性插值第二步：s = lo + ip/1024 ──────────────────
            S_INTERP2: begin
                s_int <= dlo + (ip >>> 10);
                st    <= S_ACC;
            end

            // ── 乘力度并累加 ─────────────────────────────────────
            S_ACC: begin
                acc <= acc + ((s_int * $signed({1'b0, cur_gain})) >>> 8);
                if (k == 3'd7) st <= S_OUT;
                else begin
                    k  <= k + 3'd1;
                    st <= S_ADDR;
                end
            end

            // ── 8 路 → ÷8 归一（8 路同相满幅也不会削顶）──────────
            S_OUT: begin
                sample <= acc >>> 3;
                st     <= S_IDLE;
            end

            default: st <= S_IDLE;
            endcase
        end
    end

endmodule

`default_nettype wire
